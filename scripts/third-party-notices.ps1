<#
.SYNOPSIS
  Writes THIRD_PARTY_NOTICES.md: every third-party package compiled into the shipped binaries
  (Rust crates reachable from umr, umr-core, umr-desktop, umr-elevate through normal
  dependencies) and every npm package bundled into the desktop UI, with version, licence and
  source. Offline: reads `cargo metadata` and node_modules. Run from the repository root.
#>
param([string]$Out = "THIRD_PARTY_NOTICES.md")
$ErrorActionPreference = "Stop"

$json = cargo metadata --format-version 1 --filter-platform x86_64-pc-windows-msvc --locked
if ($LASTEXITCODE -ne 0) { throw "cargo metadata failed (is Cargo.lock up to date?)" }
$meta = $json | ConvertFrom-Json
$pkgs = @{}
foreach ($p in $meta.packages) { $pkgs[$p.id] = $p }
$nodes = @{}
foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }
$workspace = @{}
foreach ($id in $meta.workspace_members) { $workspace[$id] = $true }

$roots = $meta.packages | Where-Object { $_.name -in @("umr-cli", "umr-core", "umr-desktop", "umr-elevate") } | ForEach-Object { $_.id }
$seen = @{}
$queue = [System.Collections.Generic.Queue[string]]::new()
foreach ($r in $roots) { $queue.Enqueue($r) }
while ($queue.Count -gt 0) {
  $id = $queue.Dequeue()
  if ($seen.ContainsKey($id)) { continue }
  $seen[$id] = $true
  foreach ($d in $nodes[$id].deps) {
    # normal dependencies only (no dev / build): what ends up in the binaries
    if ($d.dep_kinds | Where-Object { $null -eq $_.kind }) { $queue.Enqueue($d.pkg) }
  }
}

$rust = $seen.Keys | Where-Object { -not $workspace.ContainsKey($_) } | ForEach-Object { $pkgs[$_] } |
  Sort-Object name, version
$npmRoot = "apps/desktop/ui/node_modules"
$npmNames = @("react", "react-dom", "scheduler", "loose-envify", "js-tokens", "@tauri-apps/api")
$npm = foreach ($n in $npmNames) {
  $f = Join-Path $npmRoot "$n/package.json"
  if (Test-Path $f) { Get-Content $f -Raw | ConvertFrom-Json }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("# Third-party notices")
$lines.Add("")
$lines.Add("AI Mobile Runtime includes the following third-party software. Each package is used under its own licence, named below; the full licence texts are in each package's source repository and in the crates.io / npm package. Generated by ``scripts/third-party-notices.ps1`` - do not edit by hand.")
$lines.Add("")
$lines.Add("Tools the runtime downloads at the user's request (JDK, Android SDK and emulator, Flutter, Node.js, Gradle and others) are not part of this distribution; their licences are shown in the app before they are installed.")
$lines.Add("")
$lines.Add("## Rust crates ($($rust.Count))")
$lines.Add("")
$lines.Add("| Crate | Version | Licence | Source |")
$lines.Add("|---|---|---|---|")
foreach ($p in $rust) {
  $lic = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { "unknown" }
  $src = if ($p.repository) { $p.repository } else { "https://crates.io/crates/$($p.name)" }
  $lines.Add("| $($p.name) | $($p.version) | $lic | $src |")
}
$lines.Add("")
$lines.Add("## npm packages in the desktop UI ($(@($npm).Count))")
$lines.Add("")
$lines.Add("| Package | Version | Licence |")
$lines.Add("|---|---|---|")
foreach ($p in $npm) { $lines.Add("| $($p.name) | $($p.version) | $($p.license) |") }
$lines.Add("")
[System.IO.File]::WriteAllText((Join-Path (Get-Location) $Out), ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
$unknown = @($rust | Where-Object { -not $_.license -and -not $_.license_file }).Count
Write-Host "${Out}: $($rust.Count) crates, $(@($npm).Count) npm packages, $unknown without a licence field"
if ($unknown -gt 0) { exit 1 }
